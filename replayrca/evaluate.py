"""Evaluate diagnoser models on harvested failures by counterfactual replay.

python -m replayrca.evaluate --models anthropic/claude-opus-5.5,openai/gpt-6.1-sol --k 3

For each item the diagnoser sees the failed trajectory and returns (step, replacement action).
The environment is restored just before that step, the replacement is executed, and the
original worker continues on its own k times. Score = success rate of those continuations.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import re
import threading
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

from . import agent, env, llm, media, replay

ROOT = Path(__file__).resolve().parent.parent
BASELINE = "baseline/replay-original-random"

DIAG_SYSTEM = "You are an expert at debugging autonomous AI agents."
DIAG_TEMPLATE = """An AI agent attempted the task below in a simulated back-office environment and FAILED the automatic \
acceptance check (the check's details are withheld from you).

## Task given to the agent
{prompt}

## Agent's system prompt
{system}

## Tools available to the agent
{tools}

## Full trajectory ({n} steps)
{trajectory}

## Your job
Find the decisive mistake and correct it with ONE action.
We will restore the environment exactly as it was just before the step you choose, execute your replacement action \
INSTEAD of the agent's original action at that step, show the agent the result, and then let the SAME agent continue \
entirely on its own: every later step is regenerated by the agent. You get credit if the agent then completes the task \
correctly. The continuation is sampled several times and your score is its success rate.

Rules:
- Exactly one replacement action: one of the tools above, with valid arguments.
- You cannot talk to the agent. Free-text arguments 'reason' and 'summary' are discarded; 'query', 'subject' and \
'body' are truncated.
- The original action at your chosen step is discarded; earlier steps are kept as they were.

Answer with a single JSON object and nothing else:
{{"diagnosis": "<what went wrong, 1-3 sentences>", "step": <step number between 1 and {n}>, \
"replacement": {{"tool": "<tool name>", "args": {{...}}}}}}"""


# Reworded prompt for the prompt-sensitivity ablation (variant "#alt"): same information and the same answer format,
# different framing, order and wording.
DIAG_SYSTEM_ALT = "You are a reliability engineer who reviews incidents involving autonomous software agents."
DIAG_TEMPLATE_ALT = """Incident review. The autonomous agent whose run is transcribed below did not pass the automatic \
acceptance check for its task (what the check found is not disclosed). Your review must identify the single point at \
which one different action would have put the run back on course, and specify that action.

How your answer is evaluated: the environment is reset to its exact state just before the step you name; your action \
is executed there instead of the agent's; its result is shown to the agent; the agent then carries on alone, \
regenerating every subsequent step. This replay is repeated several times and you are scored by the fraction of \
replays in which the agent completes the task correctly.

Constraints: name one step between 1 and {n} and one tool call with valid arguments; you cannot send instructions \
to the agent (the free-text arguments 'reason' and 'summary' are dropped, and 'query', 'subject' and 'body' are \
truncated); the steps before the one you name are kept unchanged, and the agent's original action at that step is \
dropped.

## Task given to the agent
{prompt}

## Agent's system prompt
{system}

## Tools available to the agent
{tools}

## Transcript ({n} steps)
{trajectory}

Reply with exactly one JSON object and no other text:
{{"diagnosis": "<root cause, 1-3 sentences>", "step": <integer>, \
"replacement": {{"tool": "<tool name>", "args": {{...}}}}}}"""


def slug(model: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]", "_", model)


TRAJ_MARK = "<<<TRAJECTORY>>>"


def render_trajectory(traj: dict, footer: str | None = None) -> list[dict]:
    """Trajectory as content parts: text, plus the images the agent saw (as image_ref parts)."""
    parts, buf = [], []
    for i, s in enumerate(traj["steps"], 1):
        block = [f"### Step {i}"]
        if s.get("thought"):
            block.append(f"Agent note: {s['thought'].strip()[:1500]}")
        block.append(f"Action: {s['tool']}({s['args_raw']})")
        block.append(f"Observation: {s['observation']}")
        buf.append("\n".join(block))
        if s.get("image"):
            parts.append({"type": "text", "text": "\n\n".join(buf) + f"\n[Image {s['image']} as seen by the agent:]"})
            parts.append({"type": "image_ref", "attachment_id": s["image"]})
            buf = []
    end = footer if footer is not None else {
        "finish": "The agent called finish.", "no_tool_call": "The agent stopped without calling finish.",
        "max_steps": "The agent ran out of steps."}.get(traj["end"], f"Episode ended: {traj['end']}")
    buf.append(end)
    parts.append({"type": "text", "text": "\n\n".join(buf)})
    return parts


def build_prompt(item: dict, task: dict, template: str = DIAG_TEMPLATE) -> list[dict]:
    head, tail = template.format(prompt=task["prompt"], system=agent.SYSTEM_PROMPT,
                                 tools=env.tool_reference(task), n=len(item["traj"]["steps"]),
                                 trajectory=TRAJ_MARK).split(TRAJ_MARK)
    parts = render_trajectory(item["traj"])
    parts[0] = {"type": "text", "text": head + parts[0]["text"]}
    parts[-1] = {"type": "text", "text": parts[-1]["text"] + tail}
    return parts


def parse_answer(text: str):
    text = text or ""
    candidates = re.findall(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.S)
    if "{" in text and "}" in text[text.index("{"):]:
        candidates.append(text[text.index("{"): text.rindex("}") + 1])
    for c in candidates:
        try:
            obj = json.loads(c)
            if isinstance(obj, dict):
                return obj
        except json.JSONDecodeError:
            continue
    return None


JSON_REMINDER = ("Your previous reply could not be parsed. Reply again with ONLY the JSON object in the required "
                 "format, nothing else.")


def ask_json(model: str, messages: list[dict], *, max_tokens: int, extra, tag: str):
    """One call, plus one re-ask if the reply is not a JSON object (not when the output was truncated).
    Returns (response with summed cost/usage, parsed object or None, whether a re-ask happened)."""
    r = llm.chat(model, messages, max_tokens=max_tokens, extra=extra, tag=tag)
    ans = parse_answer(r["message"].get("content") or "")
    if isinstance(ans, dict) or r.get("finish_reason") == "length":
        return r, ans, False
    follow = messages + [{"role": "assistant", "content": r["message"].get("content") or ""},
                         {"role": "user", "content": JSON_REMINDER}]
    r2 = llm.chat(model, follow, max_tokens=max_tokens, extra=extra, tag=tag + ":json-retry")
    u1, u2 = r["usage"] or {}, r2["usage"] or {}
    usage = {k: (u1.get(k) or 0) + (u2.get(k) or 0) for k in ("prompt_tokens", "completion_tokens")}
    usage["completion_tokens_details"] = {"reasoning_tokens": sum(
        ((u.get("completion_tokens_details") or {}).get("reasoning_tokens") or 0) for u in (u1, u2))}
    r2 = {**r2, "cost": r["cost"] + r2["cost"], "usage": usage}
    return r2, parse_answer(r2["message"].get("content") or ""), True


def validate(ans, n_steps: int, task: dict):
    """Returns (t0, tool, args, flags) or raises ValueError."""
    if not isinstance(ans, dict):
        raise ValueError("no JSON object")
    try:
        step = int(ans.get("step"))
    except (TypeError, ValueError):
        raise ValueError("step is not an integer")
    if not 1 <= step <= n_steps:
        raise ValueError("step out of range")
    rep = ans.get("replacement") or {}
    tool, args = rep.get("tool"), rep.get("args", {})
    if tool not in env.tool_names(task):
        raise ValueError("unknown tool")
    if not isinstance(args, dict):
        raise ValueError("args is not an object")
    args, flags = replay.sanitize(tool, args)
    return step - 1, tool, args, flags


def rollout_key(item_id, t, tool, args):
    return hashlib.sha1(json.dumps([item_id, t, tool, args], sort_keys=True).encode()).hexdigest()[:20]


class JsonlCache:
    def __init__(self, path: Path, key: str):
        self.path, self.key, self.lock = path, key, threading.Lock()
        self.data, self.skipped = {}, 0
        if path.exists():
            for line in path.read_text(encoding="utf-8").splitlines():
                if not line.strip():
                    continue
                try:
                    rec = json.loads(line)
                except json.JSONDecodeError:
                    self.skipped += 1  # a line still being written by another process; it is re-done, never trusted
                    continue
                self.data[rec[key]] = rec

    def put(self, rec):
        with self.lock:
            self.data[rec[self.key]] = rec
            with open(self.path, "a", encoding="utf-8") as f:
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")


def load_items(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def task_of(item: dict) -> dict:
    t = item["task"]
    task = env.generate(t["template"], t["seed"], t["difficulty"])
    if task["state_hash"] != t["state_hash"]:
        raise RuntimeError(f"generator changed since harvest for {t['task_id']}")
    return task


def diagnose(model: str, item: dict, task: dict, cache: JsonlCache) -> dict:
    cid = f"{model}|{item['item_id']}"
    if cid in cache.data:
        return cache.data[cid]
    rec = {"id": cid, "model": model, "item_id": item["item_id"]}
    n = len(item["traj"]["steps"])
    if model == BASELINE:
        rng = random.Random(item["item_id"])
        t = rng.randrange(n)
        s = item["traj"]["steps"][t]
        rec.update(raw="", cost=0.0, diagnosis="(replay the original action at a random step)")
        if s["args"] is None:
            rec.update(valid=False, error="original args invalid")
        else:
            args, flags = replay.sanitize(s["tool"], s["args"])
            rec.update(valid=True, t=t, tool=s["tool"], args=args, flags=flags)
        cache.put(rec)
        return rec
    # "provider/model@effort#variant": effort pins the reasoning effort (low|medium|high). Variants: "last" forces the
    # intervention onto the final step (structural baseline: most failures are labelled at the last step); "alt" uses
    # the reworded prompt (prompt-sensitivity ablation); "rep<N>" repeats the diagnosis with the same prompt under a
    # new cache key (test-retest: a second sample of the diagnoser).
    spec, _, variant = model.partition("#")
    if variant and variant not in ("last", "alt") and not re.fullmatch(r"rep\d+", variant):
        raise ValueError(f"unknown variant '#{variant}' in {model}")
    base, _, effort = spec.partition("@")
    extra = llm.reasoning_extra(base, effort)
    try:
        alt = variant == "alt"
        user = {"role": "user", "content": build_prompt(item, task, DIAG_TEMPLATE_ALT if alt else DIAG_TEMPLATE)}
        if variant == "last":
            user["content"].append({"type": "text", "text": f"\nConstraint: you MUST choose step {n} (the final step)."})
        vision = llm.supports_images(base)
        rec["vision"] = vision
        msgs = [{"role": "system", "content": DIAG_SYSTEM_ALT if alt else DIAG_SYSTEM}] + media.expand([user], task, vision)
        r, ans, retried = ask_json(base, msgs, max_tokens=llm.output_budget(base, effort), extra=extra,
                                   tag=f"diagnose:{item['item_id']}")
    except llm.BudgetExceeded:
        raise
    except llm.LLMError as e:
        rec.update(valid=False, error=f"api: {str(e)[:300]}", cost=0.0, raw="")
        return rec  # not cached: retried on the next run
    text = r["message"].get("content") or ""
    rec.update(raw=text[:4000], cost=r["cost"], usage=r["usage"], json_retry=retried,
               finish_reason=r.get("finish_reason"))
    try:
        t, tool, args, flags = validate(ans, n, task)
        if variant == "last" and t != n - 1:
            raise ValueError("variant 'last' requires the final step")
        rec.update(valid=True, t=t, tool=tool, args=args, flags=flags, diagnosis=str(ans.get("diagnosis", ""))[:1000])
    except ValueError as e:
        rec.update(valid=False, error=str(e))
    cache.put(rec)
    return rec


def placebo_of(item: dict, t: int):
    """Null intervention at step t: the agent's own original action, replayed through the same mechanism."""
    s = item["traj"]["steps"][t]
    return (s["tool"], s["args"]) if s["args"] is not None else None


# Caps concurrent worker continuations across all threads (each continuation is a sequential episode).
ROLLOUT_SLOTS = threading.BoundedSemaphore(int(os.environ.get("REPLAYRCA_PARALLEL", "32")))


def _one_rollout(item, task, t, tool, args) -> dict:
    for _ in range(3):
        with ROLLOUT_SLOTS:
            tr = replay.continue_with(task, item["traj"], t, tool, args, tag=f"rollout:{item['item_id']}")
        if not (tr["end"].startswith("api_error") or tr["end"] == "truncated"):
            return tr
    raise llm.LLMError(f"rollout artefact: {tr['end'][:200]}")


def run_rollouts(item, task, t, tool, args, k, cache: JsonlCache) -> dict:
    """k continuations after replacing step t by (tool, args); missing ones run in parallel, results cached."""
    key = rollout_key(item["item_id"], t, tool, args)
    prev = cache.data.get(key)
    if prev and len(prev["outcomes"]) >= k:
        return prev
    prev = prev or {"outcomes": [], "violations": [], "ends": [], "cost": 0.0}
    need = k - len(prev["outcomes"])
    with ThreadPoolExecutor(need) as pool:
        trs = list(pool.map(lambda _: _one_rollout(item, task, t, tool, args), range(need)))
    rec = {"key": key, "item_id": item["item_id"], "t": t, "tool": tool, "args": args,
           "outcomes": prev["outcomes"] + [tr["passed"] for tr in trs],
           "violations": prev.get("violations", []) + [tr["violations"][:5] for tr in trs],
           "ends": prev.get("ends", []) + [tr["end"] for tr in trs],
           "cost": prev.get("cost", 0.0) + sum(tr["cost"] for tr in trs)}
    cache.put(rec)
    return rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", required=True, help=f"comma-separated OpenRouter ids; '{BASELINE}' for the baseline")
    ap.add_argument("--items", default="data/items.jsonl")
    ap.add_argument("--k", type=int, default=3)
    ap.add_argument("--threads", type=int, default=12)
    ap.add_argument("--budget", type=float, default=10.0)
    ap.add_argument("--effort", default="", help="reasoning effort applied to every model without an explicit @effort")
    ap.add_argument("--no-placebo", action="store_true", help="skip the paired null-intervention rollouts")
    a = ap.parse_args()

    runs = ROOT / "runs"
    runs.mkdir(exist_ok=True)
    llm.BUDGET.limit, llm.BUDGET.log_path = a.budget, runs / "calls.jsonl"
    items = load_items(ROOT / a.items)
    tasks = {it["item_id"]: task_of(it) for it in items}
    models = [m.strip() for m in a.models.split(",") if m.strip()]
    if a.effort:  # e.g. "high", or "top" = each model's own maximum supported effort
        models = [m if m == BASELINE else llm.resolve_effort(m, a.effort) for m in models]
        print("models:", ", ".join(models))
    diag_cache = JsonlCache(runs / "diagnoses.jsonl", "id")
    roll_cache = JsonlCache(runs / "rollouts.jsonl", "key")

    print(f"{len(items)} items, {len(models)} models, k={a.k}")
    by_item = {it["item_id"]: it for it in items}
    roll_futs, roll_lock = {}, threading.Lock()

    def log_rollout(f):
        try:
            r = f.result()
            print(f"[{llm.BUDGET.spent:7.3f}$] rollout {r['item_id'][:44]:44s} step {r['t'] + 1} {r['tool']:16s} "
                  f"{sum(r['outcomes'])}/{len(r['outcomes'])}", flush=True)
        except llm.BudgetExceeded as e:
            print(f"STOP: {e}", flush=True)
        except Exception as e:  # noqa: BLE001 - one failed rollout must never stop the run (it is retried next run)
            print(f"rollout failed ({type(e).__name__}): {str(e)[:200]}", flush=True)

    # Pipelined: each intervention is rolled out as soon as its diagnosis is available (shared, de-duplicated).
    with ThreadPoolExecutor(a.threads) as diag_pool, ThreadPoolExecutor(a.threads) as roll_pool:
        futs = [diag_pool.submit(diagnose, m, it, tasks[it["item_id"]], diag_cache) for m in models for it in items]
        for f in as_completed(futs):
            try:
                d = f.result()
            except llm.BudgetExceeded as e:
                print(f"STOP: {e}", flush=True)
                continue
            except Exception as e:  # noqa: BLE001
                print(f"diagnosis failed ({type(e).__name__}): {str(e)[:200]}", flush=True)
                continue
            status = f"step {d['t'] + 1} {d['tool']}" if d.get("valid") else f"INVALID ({d.get('error')})"
            print(f"[{llm.BUDGET.spent:7.3f}$] diag {d['model'][:34]:34s} {d['item_id'][:44]:44s} {status}", flush=True)
            if d.get("valid"):
                item = by_item[d["item_id"]]
                actions = [(d["tool"], d["args"])]
                if not a.no_placebo and placebo_of(item, d["t"]):
                    actions.append(placebo_of(item, d["t"]))
                for tool, args in actions:
                    key = rollout_key(d["item_id"], d["t"], tool, args)
                    with roll_lock:
                        if key not in roll_futs:
                            roll_futs[key] = roll_pool.submit(run_rollouts, item, tasks[d["item_id"]], d["t"], tool,
                                                              args, a.k, roll_cache)
                            roll_futs[key].add_done_callback(log_rollout)
        print(f"\nAll diagnoses done; {len(roll_futs)} unique interventions being rolled out", flush=True)
    print(f"\nTotal spent this run: ${llm.BUDGET.spent:.3f}")
    from . import report
    report.main(items_path=ROOT / a.items, models=models, k=a.k, stem="leaderboard_last_run")


if __name__ == "__main__":
    main()
